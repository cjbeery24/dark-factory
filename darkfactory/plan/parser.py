"""Markdown plan table parsing.

Replaces parse_plan() from dark-factory-plan.sh — parses the plan markdown
table and reads depends-on metadata from individual spec files.

Expects the plan table format generated by /df-write-plan:
  | ID | Feature Name | Spec Type | Depends On | Description |
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

from darkfactory.errors import ConfigError
from darkfactory.models.plan import PlanSpec

log = logging.getLogger(__name__)

# Matches a table separator row: | --- | --- | ... |
_TABLE_SEP_RE = re.compile(r'^\s*\|[\s-]+\|')
# Matches the feature decomposition table header: first column "ID", second contains "Feature"
_TABLE_HEADER_RE = re.compile(r'^\|\s*ID\s*\|[^|]*Feature', re.IGNORECASE)
# Matches a table data row: | value | value | ... |
_TABLE_ROW_RE = re.compile(r'^\|')
# Matches depends-on metadata in a spec file (plain line or inside comment block)
_DEPENDS_ON_RE = re.compile(r'^depends-on:\s*\[([^\]]*)\]')
# Matches a feature ID like F-1, F-12 (uppercase letter, dash, digits)
_FEATURE_ID_RE = re.compile(r'^[A-Z]-\d+$')


def _slugify(text: str) -> str:
    """Convert a feature name to a kebab-case spec name slug."""
    return re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')


def parse_plan(
    plan_file: Path,
    project_dir: Path,
) -> list[PlanSpec]:
    """Parse a plan markdown file into a list of PlanSpec objects.

    Expects the table format generated by /df-write-plan:
      | ID | Feature Name | Spec Type | Depends On | Description |

    After parsing, reads depends-on metadata from each spec file
    as the source of truth for dependencies (overrides the table).

    Raises ConfigError on invalid plans (no specs, duplicates, bad names,
    unknown dependencies).
    """
    specs, id_to_name = _parse_table(plan_file)

    if not specs:
        raise ConfigError(f"no specs found in plan file: {plan_file}")

    # Override deps from individual spec metadata.
    _apply_spec_metadata(specs, project_dir, id_to_name)

    # Validate all dependencies reference known specs.
    spec_names = {s.name for s in specs}
    for spec in specs:
        for dep in spec.deps:
            if dep not in spec_names:
                raise ConfigError(
                    f"spec {spec.name!r} depends on unknown spec {dep!r}"
                )

    # Parse target_files from spec metadata.
    for spec in specs:
        spec_file = _find_spec_file(project_dir, spec.name)
        if spec_file is not None:
            spec.target_files = parse_target_files(spec_file)

    return specs


def _parse_table(plan_file: Path) -> tuple[list[PlanSpec], dict[str, str]]:
    """Parse the feature decomposition table from the plan file.

    Returns (specs, id_to_name) where id_to_name maps feature IDs
    (e.g. "F-1") to spec names (e.g. "project-scaffolding").
    """
    specs: list[PlanSpec] = []
    seen_names: set[str] = set()
    id_to_name: dict[str, str] = {}
    in_table = False

    # Column indices — detected from header row.
    id_col: int = 0
    name_col: int = 1
    deps_col: int | None = None

    for line in plan_file.read_text().splitlines():
        # Skip empty lines and headings.
        if not line.strip() or line.strip().startswith("#"):
            continue

        # Skip table separator rows.
        if _TABLE_SEP_RE.match(line):
            continue

        if not in_table:
            if _TABLE_HEADER_RE.match(line):
                in_table = True
                cells = [c.strip() for c in line.strip().strip("|").split("|")]
                lower = [c.lower() for c in cells]
                id_col = 0
                # Find the feature name column.
                name_col = 1  # default
                for i, c in enumerate(lower):
                    if i > 0 and ("feature" in c or c in ("name", "spec")):
                        name_col = i
                        break
                # Find the depends-on column.
                for i, c in enumerate(lower):
                    if "depend" in c:
                        deps_col = i
                        break
            continue

        # We're inside the table.
        if not _TABLE_ROW_RE.match(line):
            break  # Non-table line — stop.

        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if not cells or not cells[0].strip():
            continue

        fid = cells[id_col].strip() if id_col < len(cells) else ""
        if not _FEATURE_ID_RE.match(fid):
            continue  # Skip non-feature rows (blank, malformed).

        fname = cells[name_col].strip() if name_col < len(cells) else ""
        if not fname:
            continue

        name = _slugify(fname)
        if not name:
            continue

        # Collect raw deps as IDs — resolved to names after table parse.
        raw_deps: list[str] = []
        if deps_col is not None and deps_col < len(cells):
            dep_str = cells[deps_col].strip()
            if dep_str and dep_str not in ("—", "-", "none", "None"):
                raw_deps = [d.strip() for d in dep_str.split(",") if d.strip()]

        id_to_name[fid] = name

        if name in seen_names:
            log.warning("duplicate spec name %r in plan (from %s) — skipping", name, fid)
            continue
        seen_names.add(name)
        specs.append(PlanSpec(name=name, deps=raw_deps, priority=99))

    # Resolve dep IDs to spec names.
    for spec in specs:
        resolved = []
        for dep in spec.deps:
            if dep in id_to_name:
                resolved.append(id_to_name[dep])
            else:
                log.warning("unknown dep ID %r for spec %r — skipping", dep, spec.name)
        spec.deps = resolved

    return specs, id_to_name


def _find_spec_file(project_dir: Path, spec_name: str) -> Path | None:
    """Find a spec file by name, handling date-prefixed filenames."""
    specs_dir = project_dir / ".dark-factory" / "specs"
    # Try exact name first.
    exact = specs_dir / f"{spec_name}.md"
    if exact.exists():
        return exact
    # Try date-prefixed variants (e.g. 2026-03-24-spec-name.md).
    candidates = sorted(specs_dir.glob(f"????-??-??-{spec_name}.md"))
    return candidates[0] if candidates else None


def _apply_spec_metadata(
    specs: list[PlanSpec],
    project_dir: Path,
    id_to_name: dict[str, str] | None = None,
) -> None:
    """Override deps from individual spec file metadata blocks.

    Handles both plain-line and HTML comment block metadata formats.
    Resolves ID-based deps (F-1, F-2) to spec names using id_to_name.
    """
    for spec in specs:
        spec_file = _find_spec_file(project_dir, spec.name)
        if spec_file is None:
            log.warning("spec file not found for %r", spec.name)
            continue

        for line in spec_file.read_text().splitlines():
            m = _DEPENDS_ON_RE.match(line.strip())
            if m:
                raw = m.group(1).strip()
                if raw:
                    raw_deps = [d.strip() for d in raw.split(",") if d.strip()]
                    if id_to_name:
                        # Resolve ID deps to spec names; drop unknown IDs.
                        spec.deps = [
                            id_to_name[d] for d in raw_deps if d in id_to_name
                        ]
                    else:
                        spec.deps = raw_deps
                else:
                    spec.deps = []
                break


def parse_target_files(spec_file: Path) -> list[str]:
    """Extract target-files from a spec's YAML metadata block.

    Expects a block like:
        target-files:
          - src/foo.ts
          - src/bar.ts

    Returns list of file paths.
    """
    files: list[str] = []
    in_target_files = False

    for line in spec_file.read_text().splitlines():
        if line.startswith("target-files:"):
            in_target_files = True
            continue

        if in_target_files:
            # End of block: non-indented line.
            if not line.startswith(" ") and not line.startswith("\t"):
                break
            stripped = line.strip()
            if stripped.startswith("- "):
                files.append(stripped[2:].strip())

    return files
