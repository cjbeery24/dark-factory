"""Append-only delta log for the environment contract.

Phase 2.2. Each delta lives at
``.dark-factory/architecture/environment.deltas/NNNN-<spec>.toml`` and
records a set of structured ``[[ops]]`` against the environment view as it
existed when the Architect read it. The materialized
``.dark-factory/architecture/environment.toml`` is regenerated by replaying
the delta log in lexicographic filename order.

Delta TOML shape::

    schema_version = 1
    spec_id = "2026-03-28-api-bootstrap"
    parent_hash = "<sha256 of canonical_dump(view) at architect read time>"
    applied_at = "2026-04-06T20:34:00Z"

    [[ops]]
    op = "set"          # set | modify | remove
    path = "runtime.language"
    value = "typescript"

``op`` semantics:
  - ``set``: create or overwrite (used in bootstrap and routine writes)
  - ``modify``: overwrite an already-set value (rejected if currently default)
  - ``remove``: reset to dataclass default

Determinism rules:
  - Folds are deterministic: same delta files in same dir = identical view.
  - Filename ordering is *lexicographic*. Numeric prefix
    (``0001-``, ``0002-``) is required so cardinality and order match.
  - Each delta's ``parent_hash`` MUST equal the hash of the materialized
    view *immediately before* it is applied. Mismatch raises
    ``EnvironmentConflict``.
"""

from __future__ import annotations

import hashlib
import os
import tempfile
import tomllib
from dataclasses import dataclass, field, fields, is_dataclass
from pathlib import Path
from typing import Any

from darkfactory.architecture.environment import (
    ALLOWED_PATHS,
    EnvironmentContract,
    ServiceEntry,
    canonical_dump,
    is_allowed_path,
    validate_environment,
)


SCHEMA_VERSION = 2
_ACCEPTED_SCHEMA_VERSIONS = frozenset({1, 2})
_VALID_OPS = frozenset({"set", "modify", "remove"})


class EnvironmentConflict(Exception):
    """Raised when a delta cannot be applied (parent_hash drift, forbidden path,
    or schema violation). Halts the fold — never partially applied."""


class TargetHashNotReached(EnvironmentConflict):
    """Raised by fold_to_hash when the requested hash never appears.

    Separate subclass (not substring-sniffed from a message) so callers
    like the Phase 6.3 smoke probe can distinguish 'stranded prior ship'
    from 'delta log is corrupt'. The former is a human decision; the
    latter is an immediate abort.
    """


@dataclass
class DeltaOp:
    op: str
    path: str
    value: Any = None


@dataclass
class Delta:
    schema_version: int
    spec_id: str
    parent_hash: str
    applied_at: str
    ops: list[DeltaOp] = field(default_factory=list)
    source_path: Path | None = None  # populated by load_delta for diagnostics


# ----- Hashing ---------------------------------------------------------------


def hash_view(contract: EnvironmentContract) -> str:
    """sha256(canonical_dump(contract)) as lowercase hex."""
    return hashlib.sha256(canonical_dump(contract)).hexdigest()


# ----- Loading ---------------------------------------------------------------


def load_delta(path: Path) -> Delta:
    """Parse a delta TOML file. Raises EnvironmentConflict on schema violation."""
    try:
        raw = tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError, UnicodeDecodeError) as exc:
        raise EnvironmentConflict(f"{path.name}: cannot parse: {exc}") from exc

    try:
        schema_version = raw["schema_version"]
        spec_id = raw["spec_id"]
        parent_hash = raw["parent_hash"]
        applied_at = raw["applied_at"]
    except KeyError as exc:
        raise EnvironmentConflict(f"{path.name}: missing required key {exc}") from exc

    if schema_version not in _ACCEPTED_SCHEMA_VERSIONS:
        raise EnvironmentConflict(
            f"{path.name}: schema_version {schema_version} not in "
            f"{sorted(_ACCEPTED_SCHEMA_VERSIONS)}",
        )

    raw_ops = raw.get("ops", [])
    if not isinstance(raw_ops, list):
        raise EnvironmentConflict(f"{path.name}: ops must be a list")

    ops: list[DeltaOp] = []
    for i, raw_op in enumerate(raw_ops):
        if not isinstance(raw_op, dict):
            raise EnvironmentConflict(f"{path.name}: ops[{i}] must be a table")
        op_name = raw_op.get("op")
        op_path = raw_op.get("path")
        if op_name not in _VALID_OPS:
            raise EnvironmentConflict(
                f"{path.name}: ops[{i}].op = {op_name!r} (must be set/modify/remove)",
            )
        # v1 deltas: static allowlist only. v2 deltas: static + service paths.
        if not isinstance(op_path, str):
            raise EnvironmentConflict(
                f"{path.name}: ops[{i}].path must be a string",
            )
        if schema_version == 1 and op_path not in ALLOWED_PATHS:
            raise EnvironmentConflict(
                f"{path.name}: ops[{i}].path = {op_path!r} not in allowlist",
            )
        if schema_version >= 2 and not is_allowed_path(op_path):
            raise EnvironmentConflict(
                f"{path.name}: ops[{i}].path = {op_path!r} not in allowlist",
            )
        ops.append(DeltaOp(op=op_name, path=op_path, value=raw_op.get("value")))

    return Delta(
        schema_version=schema_version,
        spec_id=spec_id,
        parent_hash=parent_hash,
        applied_at=applied_at,
        ops=ops,
        source_path=path,
    )


_NUMERIC_PREFIX_LEN = 4


def list_deltas(deltas_dir: Path) -> list[Path]:
    """Return delta files in lexicographic order. Empty list if dir absent.

    Rejects duplicate numeric prefixes (e.g. two ``0002-*.toml`` files) since
    that would let two racing Architects with the same parent_hash both fold
    cleanly with one silently winning.
    """
    if not deltas_dir.is_dir():
        return []
    paths = sorted(
        p for p in deltas_dir.iterdir() if p.is_file() and p.suffix == ".toml"
    )
    seen: dict[str, str] = {}
    for p in paths:
        prefix = p.name[:_NUMERIC_PREFIX_LEN]
        if prefix in seen:
            raise EnvironmentConflict(
                f"duplicate delta numeric prefix {prefix!r}: "
                f"{seen[prefix]} and {p.name}",
            )
        seen[prefix] = p.name
    return paths


# ----- Apply -----------------------------------------------------------------


def _split_path(path: str) -> tuple[str, ...]:
    """Split a dotted path into its components.

    Returns 2 parts for standard paths (``runtime.language``) and 3 parts
    for service paths (``services.postgres.image``).
    """
    return tuple(path.split("."))


def _apply_service_op(
    contract: EnvironmentContract, op: DeltaOp, source: str,
) -> None:
    """Apply an op to a service path (``services.<name>.<field>``).

    Design note: removing individual fields (e.g. ``remove services.postgres.health_cmd``)
    resets that field to its default but does NOT auto-prune the ServiceEntry from the dict.
    A ServiceEntry with all-default fields after field-level removes will still exist in
    ``contract.services`` and affect the hash. Use the 2-level ``remove services.postgres``
    to fully delete a service entry.
    """
    parts = _split_path(op.path)
    if len(parts) == 2:
        # services.<name> — only remove (delete entire service entry)
        _, svc_name = parts
        if op.op != "remove":
            raise EnvironmentConflict(
                f"{source}: services.{svc_name} (no field) only supports remove",
            )
        if svc_name not in contract.services:
            raise EnvironmentConflict(
                f"{source}: remove on services.{svc_name} but service does not exist",
            )
        del contract.services[svc_name]
        return

    if len(parts) != 3:
        raise EnvironmentConflict(f"{source}: malformed service path {op.path!r}")

    _, svc_name, field_name = parts
    fresh = ServiceEntry()
    if not any(f.name == field_name for f in fields(ServiceEntry)):
        raise EnvironmentConflict(
            f"{source}: unknown service field {field_name!r} in {op.path!r}",
        )

    entry = contract.services.get(svc_name)
    fresh_default = getattr(fresh, field_name)

    if op.op == "remove":
        if entry is None or getattr(entry, field_name) == fresh_default:
            raise EnvironmentConflict(
                f"{source}: remove on {op.path} but current value is already default",
            )
        setattr(entry, field_name, fresh_default)
        return

    if op.value is None:
        raise EnvironmentConflict(
            f"{source}: op {op.op} on {op.path} requires a value",
        )

    # Type validation.
    type_errors = validate_environment({op.path: op.value}, "bootstrap")
    if type_errors:
        raise EnvironmentConflict(
            f"{source}: {op.path} type-invalid: {type_errors[0].reason}",
        )

    current = getattr(entry, field_name) if entry is not None else fresh_default

    if op.op == "modify" and current == fresh_default:
        raise EnvironmentConflict(
            f"{source}: modify on {op.path} but current value is default; use set",
        )

    # Auto-create ServiceEntry on first set.
    if entry is None:
        entry = ServiceEntry()
        contract.services[svc_name] = entry

    setattr(entry, field_name, op.value)


def _apply_op(contract: EnvironmentContract, op: DeltaOp, source: str) -> None:
    parts = _split_path(op.path)
    if not parts or not all(parts):
        raise EnvironmentConflict(f"{source}: malformed path {op.path!r}")

    # Route service paths to dedicated handler.
    if parts[0] == "services":
        _apply_service_op(contract, op, source)
        return

    if len(parts) != 2:
        raise EnvironmentConflict(f"{source}: malformed path {op.path!r}")

    section_name, key = parts
    section_obj = getattr(contract, section_name, None)
    if section_obj is None or not is_dataclass(section_obj):
        raise EnvironmentConflict(f"{source}: unknown section in path {op.path!r}")
    if not any(f.name == key for f in fields(section_obj)):
        raise EnvironmentConflict(f"{source}: unknown key in path {op.path!r}")

    fresh_default = getattr(type(section_obj)(), key)
    current = getattr(section_obj, key)

    if op.op == "remove":
        if current == fresh_default:
            raise EnvironmentConflict(
                f"{source}: remove on {op.path} but current value is already default",
            )
        setattr(section_obj, key, fresh_default)
        return

    if op.value is None:
        raise EnvironmentConflict(f"{source}: op {op.op} on {op.path} requires a value")

    # Type validation: deltas are the only write path, so the allowlist +
    # type schema in environment.py must be enforced HERE or schema-poison
    # gets through. Bypass spec_type bootstrap-only restriction; that's a
    # higher-level concern enforced by validate_environment at write time.
    type_errors = validate_environment({op.path: op.value}, "bootstrap")
    if type_errors:
        raise EnvironmentConflict(
            f"{source}: {op.path} type-invalid: {type_errors[0].reason}",
        )

    if op.op == "modify" and current == fresh_default:
        raise EnvironmentConflict(
            f"{source}: modify on {op.path} but current value is default; use set",
        )

    setattr(section_obj, key, op.value)


def fold_to_hash(deltas_dir: Path, target_hash: str) -> EnvironmentContract:
    """Replay deltas and stop once the view's hash equals ``target_hash``.

    Phase 6.3 — powers the union smoke probe, which needs to reconstruct a
    previously-shipped spec's environment at its ``env_hash_at_ship`` so the
    archived scenarios run against the same contract they were written
    for. A delta removed in a later commit should not silently alter the
    replay of an earlier state.

    The target is matched against the view hash *after* each delta is
    applied, and also against the empty view (``target_hash == hash_view(
    EnvironmentContract())``) before any delta is applied — this lets a
    bootstrap spec with no deltas still probe successfully.

    Raises ``EnvironmentConflict`` if the target hash is never reached
    after folding all deltas. A parent_hash mismatch mid-fold is reraised
    unchanged — that's a corrupt log, not a missing target.
    """
    contract = EnvironmentContract()
    if hash_view(contract) == target_hash:
        return contract
    for delta_path in list_deltas(deltas_dir):
        delta = load_delta(delta_path)
        current_hash = hash_view(contract)
        if delta.parent_hash != current_hash:
            raise EnvironmentConflict(
                f"{delta_path.name}: parent_hash mismatch "
                f"(delta says {delta.parent_hash[:12]}, view is {current_hash[:12]})",
            )
        for op in delta.ops:
            _apply_op(contract, op, delta_path.name)
        if hash_view(contract) == target_hash:
            return contract
    raise TargetHashNotReached(
        f"target hash {target_hash[:12]} not reached after folding "
        f"{len(list_deltas(deltas_dir))} delta(s)",
    )


def fold_deltas(deltas_dir: Path) -> EnvironmentContract:
    """Replay every delta in lex order. Total + deterministic.

    Each delta's parent_hash must match the hash of the view immediately
    before it applies. Forbidden-path writes raise EnvironmentConflict.
    """
    contract = EnvironmentContract()
    for delta_path in list_deltas(deltas_dir):
        delta = load_delta(delta_path)
        current_hash = hash_view(contract)
        if delta.parent_hash != current_hash:
            raise EnvironmentConflict(
                f"{delta_path.name}: parent_hash mismatch "
                f"(delta says {delta.parent_hash[:12]}, view is {current_hash[:12]})",
            )
        for op in delta.ops:
            _apply_op(contract, op, delta_path.name)
    return contract


def _atomic_write_bytes(path: Path, data: bytes) -> None:
    """Write bytes via tmp + fsync + os.replace + dir fsync. Crash-safe."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(
        prefix=path.name + ".", suffix=".tmp", dir=path.parent,
    )
    tmp = Path(tmp_name)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(tmp, path)
        # fsync the parent dir so the rename is durable.
        try:
            dir_fd = os.open(path.parent, os.O_RDONLY)
            try:
                os.fsync(dir_fd)
            finally:
                os.close(dir_fd)
        except OSError:
            pass  # not all filesystems support directory fsync
    except Exception:
        tmp.unlink(missing_ok=True)
        raise


def materialize(deltas_dir: Path, out_path: Path) -> EnvironmentContract:
    """Fold + write environment.toml + .lock atomically.

    Both files are written via _atomic_write_bytes (tmp + fsync + replace)
    so a crash mid-write cannot leave the lock out of sync with the view.
    The lock is written FIRST so the worst case is "lock points at a view
    we never finished writing" — caller can detect this by re-hashing.
    """
    contract = fold_deltas(deltas_dir)
    payload = canonical_dump(contract)
    lock_path = out_path.with_suffix(out_path.suffix + ".lock")
    _atomic_write_bytes(lock_path, (hash_view(contract) + "\n").encode("ascii"))
    _atomic_write_bytes(out_path, payload)
    return contract
