"""Append-only delta log for the environment contract.

Phase 2.2. Each delta lives at
``.dark-factory/architecture/environment.deltas/NNNN-<spec>.toml`` and
records a set of structured ``[[ops]]`` against the environment view as it
existed when the Architect read it. The materialized
``.dark-factory/architecture/environment.toml`` is regenerated by replaying
the delta log in lexicographic filename order.

Delta TOML shape::

    schema_version = 1
    spec_id = "2026-03-28-api-bootstrap"
    parent_hash = "<sha256 of canonical_dump(view) at architect read time>"
    applied_at = "2026-04-06T20:34:00Z"

    [[ops]]
    op = "set"          # set | modify | remove
    path = "runtime.language"
    value = "typescript"

``op`` semantics:
  - ``set``: create or overwrite (used in bootstrap and routine writes)
  - ``modify``: overwrite an already-set value (rejected if currently default)
  - ``remove``: reset to dataclass default

Determinism rules:
  - Folds are deterministic: same delta files in same dir = identical view.
  - Filename ordering is *lexicographic*. Numeric prefix
    (``0001-``, ``0002-``) is required so cardinality and order match.
  - Each delta's ``parent_hash`` MUST equal the hash of the materialized
    view *immediately before* it is applied. Mismatch raises
    ``EnvironmentConflict``.
"""

from __future__ import annotations

import hashlib
import tomllib
from dataclasses import dataclass, field, fields, is_dataclass
from pathlib import Path
from typing import Any

from darkfactory.architecture.environment import (
    ALLOWED_PATHS,
    EnvironmentContract,
    canonical_dump,
)


SCHEMA_VERSION = 1
_VALID_OPS = frozenset({"set", "modify", "remove"})


class EnvironmentConflict(Exception):
    """Raised when a delta cannot be applied (parent_hash drift, forbidden path,
    or schema violation). Halts the fold — never partially applied."""


@dataclass
class DeltaOp:
    op: str
    path: str
    value: Any = None


@dataclass
class Delta:
    schema_version: int
    spec_id: str
    parent_hash: str
    applied_at: str
    ops: list[DeltaOp] = field(default_factory=list)
    source_path: Path | None = None  # populated by load_delta for diagnostics


# ----- Hashing ---------------------------------------------------------------


def hash_view(contract: EnvironmentContract) -> str:
    """sha256(canonical_dump(contract)) as lowercase hex."""
    return hashlib.sha256(canonical_dump(contract)).hexdigest()


# ----- Loading ---------------------------------------------------------------


def load_delta(path: Path) -> Delta:
    """Parse a delta TOML file. Raises EnvironmentConflict on schema violation."""
    try:
        raw = tomllib.loads(path.read_text())
    except (OSError, tomllib.TOMLDecodeError) as exc:
        raise EnvironmentConflict(f"{path.name}: cannot parse: {exc}") from exc

    try:
        schema_version = raw["schema_version"]
        spec_id = raw["spec_id"]
        parent_hash = raw["parent_hash"]
        applied_at = raw["applied_at"]
    except KeyError as exc:
        raise EnvironmentConflict(f"{path.name}: missing required key {exc}") from exc

    if schema_version != SCHEMA_VERSION:
        raise EnvironmentConflict(
            f"{path.name}: schema_version {schema_version} != {SCHEMA_VERSION}",
        )

    raw_ops = raw.get("ops", [])
    if not isinstance(raw_ops, list):
        raise EnvironmentConflict(f"{path.name}: ops must be a list")

    ops: list[DeltaOp] = []
    for i, raw_op in enumerate(raw_ops):
        if not isinstance(raw_op, dict):
            raise EnvironmentConflict(f"{path.name}: ops[{i}] must be a table")
        op_name = raw_op.get("op")
        op_path = raw_op.get("path")
        if op_name not in _VALID_OPS:
            raise EnvironmentConflict(
                f"{path.name}: ops[{i}].op = {op_name!r} (must be set/modify/remove)",
            )
        if not isinstance(op_path, str) or op_path not in ALLOWED_PATHS:
            raise EnvironmentConflict(
                f"{path.name}: ops[{i}].path = {op_path!r} not in allowlist",
            )
        ops.append(DeltaOp(op=op_name, path=op_path, value=raw_op.get("value")))

    return Delta(
        schema_version=schema_version,
        spec_id=spec_id,
        parent_hash=parent_hash,
        applied_at=applied_at,
        ops=ops,
        source_path=path,
    )


def list_deltas(deltas_dir: Path) -> list[Path]:
    """Return delta files in lexicographic order. Empty list if dir absent."""
    if not deltas_dir.is_dir():
        return []
    return sorted(p for p in deltas_dir.iterdir() if p.is_file() and p.suffix == ".toml")


# ----- Apply -----------------------------------------------------------------


def _split_path(path: str) -> tuple[str, str]:
    section, _, key = path.partition(".")
    return section, key


def _apply_op(contract: EnvironmentContract, op: DeltaOp, source: str) -> None:
    section_name, key = _split_path(op.path)
    if not section_name or not key:
        raise EnvironmentConflict(f"{source}: malformed path {op.path!r}")
    section_obj = getattr(contract, section_name, None)
    if section_obj is None or not is_dataclass(section_obj):
        raise EnvironmentConflict(f"{source}: unknown section in path {op.path!r}")
    if not any(f.name == key for f in fields(section_obj)):
        raise EnvironmentConflict(f"{source}: unknown key in path {op.path!r}")

    if op.op == "remove":
        fresh_section = type(section_obj)()
        setattr(section_obj, key, getattr(fresh_section, key))
        return

    if op.value is None:
        raise EnvironmentConflict(f"{source}: op {op.op} on {op.path} requires a value")

    if op.op == "modify":
        fresh_section = type(section_obj)()
        if getattr(section_obj, key) == getattr(fresh_section, key):
            raise EnvironmentConflict(
                f"{source}: modify on {op.path} but current value is default; use set",
            )

    setattr(section_obj, key, op.value)


def fold_deltas(deltas_dir: Path) -> EnvironmentContract:
    """Replay every delta in lex order. Total + deterministic.

    Each delta's parent_hash must match the hash of the view immediately
    before it applies. Forbidden-path writes raise EnvironmentConflict.
    """
    contract = EnvironmentContract()
    for delta_path in list_deltas(deltas_dir):
        delta = load_delta(delta_path)
        current_hash = hash_view(contract)
        if delta.parent_hash != current_hash:
            raise EnvironmentConflict(
                f"{delta_path.name}: parent_hash mismatch "
                f"(delta says {delta.parent_hash[:12]}, view is {current_hash[:12]})",
            )
        for op in delta.ops:
            _apply_op(contract, op, delta_path.name)
    return contract


def materialize(deltas_dir: Path, out_path: Path) -> EnvironmentContract:
    """Fold + write environment.toml. Returns the folded contract."""
    contract = fold_deltas(deltas_dir)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_bytes(canonical_dump(contract))
    lock_path = out_path.with_suffix(out_path.suffix + ".lock")
    lock_path.write_text(hash_view(contract) + "\n")
    return contract
