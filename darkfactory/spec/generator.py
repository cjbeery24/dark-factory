"""Spec generation — natural language to draft spec via template selection.

Takes a short description, classifies it into a template type, reads the
matching template, and writes a draft spec file.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

log = logging.getLogger(__name__)

# Template classification: keywords → template name.
_TEMPLATE_KEYWORDS: list[tuple[list[str], str]] = [
    # More specific templates first to avoid false positives from broad keywords.
    (["migration", "schema", "database", "alter table"], "db-migration"),
    (["vulnerability", "cve", "xss", "sql injection", "csrf"], "security-fix"),
    (["performance", "latency", "throughput", "optimize", "slow"], "performance"),
    (["integration", "third-party", "external", "sdk"], "integration"),
    (["refactor", "rename", "extract", "simplify", "clean up"], "refactor"),
    (["endpoint", "route", "api", "rest", "graphql", "webhook"], "api"),
    (["fix", "bug", "crash", "broken", "regression"], "bug-fix"),
]

# Template name → filename in templates/.
_TEMPLATE_FILES: dict[str, str] = {
    "feature": "feature-spec.md",
    "bug-fix": "bug-fix-spec.md",
    "refactor": "refactor-spec.md",
    "api": "api-spec.md",
    "db-migration": "db-migration-spec.md",
    "security-fix": "security-fix-spec.md",
    "performance": "performance-spec.md",
    "integration": "integration-spec.md",
}


def classify_template(description: str) -> str:
    """Classify a natural-language description into a template type.

    Returns the template name (e.g., "feature", "bug-fix", "api").
    """
    desc_lower = description.lower()
    for keywords, template in _TEMPLATE_KEYWORDS:
        if any(kw in desc_lower for kw in keywords):
            return template
    return "feature"


def _slugify(text: str) -> str:
    """Convert a description to a filename-safe slug."""
    slug = text.lower().strip()
    slug = re.sub(r'[^a-z0-9]+', '-', slug)
    slug = slug.strip('-')
    return slug[:60]


def generate_spec(
    description: str,
    project_dir: Path,
    *,
    template_override: str = "",
    framework_dir: Path | None = None,
) -> Path:
    """Generate a draft spec from a natural-language description.

    Args:
        description: Short description of the desired feature/fix/refactor.
        project_dir: Project root directory.
        template_override: Force a specific template instead of auto-detecting.
        framework_dir: Dark Factory framework directory (defaults to project_dir).

    Returns:
        Path to the generated spec file.
    """
    template_name = template_override or classify_template(description)
    log.info("classified %r as template: %s", description, template_name)

    # Locate template file.
    if framework_dir is None:
        framework_dir = project_dir
    template_file = _TEMPLATE_FILES.get(template_name)
    if not template_file:
        log.warning("unknown template %r, falling back to feature", template_name)
        template_file = _TEMPLATE_FILES["feature"]
        template_name = "feature"

    template_path = framework_dir / "templates" / template_file
    if not template_path.exists():
        raise FileNotFoundError(f"template not found: {template_path}")

    template_content = template_path.read_text()

    # Generate the spec content: template + description header.
    slug = _slugify(description)
    spec_content = _build_spec_content(description, template_name, template_content)

    # Write to specs directory.
    specs_dir = project_dir / ".dark-factory" / "specs"
    specs_dir.mkdir(parents=True, exist_ok=True)
    spec_path = specs_dir / f"{slug}.md"

    spec_path.write_text(spec_content)
    log.info("wrote draft spec: %s", spec_path)

    return spec_path


def _build_spec_content(
    description: str,
    template_name: str,
    template_content: str,
) -> str:
    """Build spec content from description and template."""
    lines = [
        f"# {description}",
        "",
        f"_Template: {template_name} | Generated by `dark-factory new-spec`_",
        "",
        "---",
        "",
        template_content,
    ]
    return "\n".join(lines)
